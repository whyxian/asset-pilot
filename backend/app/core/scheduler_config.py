"""定时任务与缓存配置 — 统一管理调度间隔、缓存 TTL、网络超时

设计目的：避免「同一概念在多处硬编码不同数字」的割裂。所有数据刷新/缓存/超时
相关的配置集中于此，各处引用，改一处即全局生效。

分组：
- 调度器间隔：APScheduler 触发频率
- 各市场刷新间隔：调度器内部按交易时段判断是否真刷新
- 缓存兜底 TTL：调度器故障时才触发过期
- 网络超时：各数据源拉取超时
"""


class SchedulerConfig:
    """定时任务与缓存配置 — 统一管理，避免散落"""

    # ─────────────────────────────────────────────
    # 调度器间隔（APScheduler 触发频率）
    # ─────────────────────────────────────────────
    QUOTE_REFRESH_INTERVAL = 30       # 行情调度：30s 触发一次（内部按市场判断是否真刷新）
    RATE_REFRESH_INTERVAL = 3300      # 汇率调度：55min（略低于 1h 缓存 TTL，保证用户请求永远命中）

    # ─────────────────────────────────────────────
    # 各市场刷新间隔（调度器内部判断，非交易时段用）
    # 交易时段直接按调度器间隔刷新，不看这里
    # ─────────────────────────────────────────────
    FUND_REFRESH_INTERVAL = 900          # 基金：15min（净值日更，无需高频）
    NON_TRADING_REFRESH_INTERVAL = 1800  # 股票非交易时段：30min（价格不动）

    # ─────────────────────────────────────────────
    # 缓存兜底 TTL（调度器故障时才触发过期，正常时调度器主动刷新）
    # ─────────────────────────────────────────────
    QUOTE_CACHE_TTL = 300             # 行情缓存：5min 兜底
    RATE_CACHE_TTL = 3600             # 汇率缓存：1h（数据源每小时更新）

    # ─────────────────────────────────────────────
    # 网络超时（秒）— 铁律：任何后端外部请求超时不得大于前端 axios 15s
    # ─────────────────────────────────────────────
    RATE_FETCH_TIMEOUT = 5            # 汇率拉取：5s（五级兜底充足，失败立刻走兜底）
    QUOTE_FETCH_TIMEOUT = 12          # 行情并发拉取整体熔断：12s（比前端 15s 略早）
    STOCK_API_TIMEOUT = 10            # 腾讯 A股/美股 API
    FUND_API_TIMEOUT = 15             # 天天基金 pingzhongdata
    CRYPTO_API_TIMEOUT = 10           # CoinGlass API
    PLAYWRIGHT_GOTO_TIMEOUT = 20000   # 新浪 Playwright 页面加载
    PLAYWRIGHT_SELECTOR_TIMEOUT = 10000  # 新浪 Playwright 元素等待
